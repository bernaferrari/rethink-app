/**
 * Keepout's icon, from one shape: the app's scalloped "Protected" seal with a bar across it, a
 * no-entry sign. Writes every icon the project ships from this file:
 *   PLAYWRIGHT_MODULE=… node store-listing/brand/make-icon.cjs
 * Adaptive icon layers (vector foreground, monochrome, background colour), legacy launcher and round
 * PNGs, the in-app drawable PNGs, the Play and README icon, and the web demo's favicon and social image.
 */
const fs = require('fs');
const path = require('path');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..', '..');
const res = path.join(root, 'app/src/main/res');

const PLUM = '#2E1020', PLUM_LIGHT = '#4A1A30', PLUM_DARK = '#1A0911';
const CORAL_TOP = '#FF8A7A', CORAL_BOTTOM = '#F0485A', CREAM = '#FFF6F3';

// On the 108 x 108 adaptive canvas: a 12-lobed seal (a lobe at the top) and a rounded bar.
function sealPath(cx = 54, cy = 54, r = 27.5, lobes = 12, depth = .055) {
  const points = [];
  for (let i = 0; i < 360; i++) {
    const t = i / 360 * Math.PI * 2 - Math.PI / 2, rr = r * (1 + depth * Math.cos(lobes * t));
    points.push(`${(cx + rr * Math.cos(t)).toFixed(2)},${(cy + rr * Math.sin(t)).toFixed(2)}`);
  }
  return `M${points.join('L')}Z`;
}
const SEAL = sealPath();
const BAR = 'M42.5,49.5L65.5,49.5A4.5,4.5 0 0 1 65.5,58.5L42.5,58.5A4.5,4.5 0 0 1 42.5,49.5Z';

const write = (file, text) => { fs.mkdirSync(path.dirname(file), {recursive: true}); fs.writeFileSync(file, text); console.log(path.relative(root, file)); };

// Adaptive layers.
write(path.join(res, 'drawable/ic_launcher_foreground.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- Keepout: the seal with a bar across it. Generated by store-listing/brand/make-icon.cjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="${SEAL}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="54" android:startY="25" android:endX="54" android:endY="83">
                <item android:offset="0" android:color="${CORAL_TOP}" />
                <item android:offset="1" android:color="${CORAL_BOTTOM}" />
            </gradient>
        </aapt:attr>
    </path>
    <path android:fillColor="${CREAM}" android:pathData="${BAR}" />
</vector>
`);
write(path.join(res, 'drawable/ic_launcher_monochrome.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- Keepout for themed icons: the seal with the bar cut out. Generated by store-listing/brand/make-icon.cjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="#FFFFFF" android:fillType="evenOdd" android:pathData="${SEAL}${BAR}" />
</vector>
`);
for (const name of ['ic_launcher', 'ic_launcher_round']) {
  write(path.join(res, `mipmap-anydpi-v26/${name}.xml`), `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`);
}
write(path.join(res, 'values/ic_launcher_background.xml'), `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">${PLUM}</color>
</resources>
`);

// The full icon as SVG, on the visible 72 x 72 part of the canvas.
const full = (shape = 'square') => {
  const clip = shape === 'circle' ? '<circle cx="54" cy="54" r="36"/>' : shape === 'rounded' ? '<rect x="18" y="18" width="72" height="72" rx="16"/>' : '<rect x="18" y="18" width="72" height="72"/>';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">
  <defs>
    <radialGradient id="ground" cx="36" cy="30" r="78" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="${PLUM_LIGHT}"/><stop offset="1" stop-color="${PLUM_DARK}"/></radialGradient>
    <linearGradient id="seal" x1="54" y1="25" x2="54" y2="83" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="${CORAL_TOP}"/><stop offset="1" stop-color="${CORAL_BOTTOM}"/></linearGradient>
    <clipPath id="shape">${clip}</clipPath>
  </defs>
  <g clip-path="url(#shape)">
    <rect x="0" y="0" width="108" height="108" fill="url(#ground)"/>
    <path d="${SEAL}" fill="url(#seal)"/>
    <path d="${BAR}" fill="${CREAM}"/>
  </g>
</svg>
`;
};
write(path.join(root, 'shared/src/wasmJsMain/resources/favicon.svg'), full('circle'));
write(path.join(root, 'store-listing/brand/icon.svg'), full('square'));

// The web demo's social image: the seal where the old shield was.
const og = path.join(root, 'shared/src/wasmJsMain/resources/opengraph-image.svg');
let ogText = fs.readFileSync(og, 'utf8');
ogText = ogText.replace(/\s*<linearGradient id="shield"[\s\S]*?<\/linearGradient>/, `
    <linearGradient id="seal" x1="54" y1="25" x2="54" y2="83" gradientUnits="userSpaceOnUse">
      <stop stop-color="${CORAL_TOP}"/>
      <stop offset="1" stop-color="${CORAL_BOTTOM}"/>
    </linearGradient>`);
ogText = ogText.replace(/\s*<path d="M274 112[^>]*\/>\s*<path d="m187 315[^>]*\/>|\s*<g transform="translate\(274[\s\S]*?<\/g>/, `
  <g transform="translate(274 328) scale(6.6) translate(-54 -54)">
    <path d="${SEAL}" fill="url(#seal)"/>
    <path d="${BAR}" fill="${CREAM}"/>
  </g>`);
fs.writeFileSync(og, ogText); console.log(path.relative(root, og));

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const png = async (svg, size, file) => {
    await page.setViewportSize({width: size, height: size});
    await page.setContent(`<style>html,body{margin:0;background:transparent}</style><img src="data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}" width="${size}" height="${size}" style="display:block">`);
    await page.waitForFunction(() => document.images[0].complete);
    fs.mkdirSync(path.dirname(file), {recursive: true});
    await page.screenshot({path: file, omitBackground: true, clip: {x: 0, y: 0, width: size, height: size}});
    console.log(path.relative(root, file));
  };
  const densities = {mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192};
  for (const [density, size] of Object.entries(densities)) {
    await png(full('rounded'), size, path.join(res, `mipmap-${density}/ic_launcher.png`));
    await png(full('circle'), size, path.join(res, `mipmap-${density}/ic_launcher_round.png`));
    await png(full('rounded'), size, path.join(res, `drawable-${density}/ic_launcher.png`));
  }
  // Play masks its own shape, so these are full-bleed squares.
  await png(full('square'), 512, path.join(root, 'store-listing/brand/icon.png'));
  await png(full('square'), 512, path.join(root, 'fastlane/metadata/android/en-US/images/icon.png'));
  await browser.close();
})();
